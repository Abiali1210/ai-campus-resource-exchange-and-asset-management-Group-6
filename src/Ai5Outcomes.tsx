import { useState, type FormEvent } from "react";
import { api } from "./api";
import type { Ai5Outcomes as Outcomes, Department } from "./types";

const iso = (offsetDays: number) =>
  new Date(Date.now() - offsetDays * 86_400_000).toISOString().slice(0, 10);
const ROWS: [string, "requests" | "allocations" | "transfers", string][] = [
  ["Requests submitted", "requests", "submitted"],
  ["Open requests (incl. partially fulfilled)", "requests", "open"],
  ["Fulfilled requests", "requests", "fulfilled"],
  ["Closed requests", "requests", "closed"],
  ["Canceled requests", "requests", "canceled"],
  ["Approved allocations", "allocations", "approved"],
  ["Units accepted on receipt", "allocations", "acceptedUnits"],
  ["Transfers completed", "transfers", "completed"],
  ["Transfers pending", "transfers", "pending"],
  ["Transfers canceled", "transfers", "canceled"],
  ["Transfers disputed", "transfers", "disputed"],
  ["Transfers returned", "transfers", "returned"],
];

// Calculated by the database for a chosen period and department. Read-only and
// independent of AI: it is not part of any narrative or frozen snapshot.
export function Ai5Outcomes({ departments }: { departments: Department[] }) {
  const [start, setStart] = useState(iso(30)),
    [end, setEnd] = useState(iso(0)),
    [department, setDepartment] = useState(""),
    [data, setData] = useState<Outcomes | null>(null),
    [busy, setBusy] = useState(false),
    [error, setError] = useState("");
  async function submit(e: FormEvent) {
    e.preventDefault();
    setBusy(true);
    setError("");
    try {
      setData(await api.ai5Outcomes(start, end, department || null));
    } catch (err) {
      setData(null);
      setError(err instanceof Error ? err.message : "Could not calculate.");
    } finally {
      setBusy(false);
    }
  }
  return (
    <section className="workflow-card" aria-label="Outcome breakdown">
      <h3>Outcome breakdown</h3>
      <p className="muted">
        Calculated from current records for a period and department. Completed,
        pending, canceled, disputed and returned transfers are counted
        separately. Not generated by AI.
      </p>
      <form className="report-controls" onSubmit={submit}>
        <label className="workflow-field">
          From
          <input
            type="date"
            value={start}
            max={end}
            required
            onChange={(e) => setStart(e.target.value)}
          />
        </label>
        <label className="workflow-field">
          To
          <input
            type="date"
            value={end}
            min={start}
            max={iso(0)}
            required
            onChange={(e) => setEnd(e.target.value)}
          />
        </label>
        <label className="workflow-field">
          Department
          <select
            value={department}
            onChange={(e) => setDepartment(e.target.value)}
          >
            <option value="">All departments</option>
            {departments.map((d) => (
              <option key={d.departmentId} value={d.departmentId}>
                {d.name}
              </option>
            ))}
          </select>
        </label>
        <button className="button small" disabled={busy}>
          {busy ? "Calculating…" : "Calculate"}
        </button>
      </form>
      {error && (
        <p role="alert" className="notice error">
          {error}
        </p>
      )}
      {data && (
        <table className="report-figures">
          <caption>
            {data.scope.departmentName}, {data.period.start} to{" "}
            {data.period.end}. {data.basis}.
          </caption>
          <tbody>
            {ROWS.map(([label, group, field]) => (
              <tr key={label}>
                <th scope="row">{label}</th>
                <td>{data[group][field]}</td>
              </tr>
            ))}
          </tbody>
        </table>
      )}
    </section>
  );
}
